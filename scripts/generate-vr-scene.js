#!/usr/bin/env node
/**
 * generate-vr-scene.js — Node CLI entry for the VR/AR export workflow.
 *
 * The KnowledgeGraphVRExporter service (src/services/vr-export-service.js) is a
 * browser-oriented class whose exportToFile() uses DOM/Blob APIs and cannot run
 * headless. This script is the headless counterpart: it imports the class,
 * feeds it the knowledge-graph data, and writes the GLB/GLTF artifacts to disk
 * with fs so the GitHub Actions workflow can upload them.
 *
 * Run: node scripts/generate-vr-scene.js
 * Env: EXPORT_QUALITY (low|medium|high), EXPORT_FORMAT (glb|gltf|both)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { KnowledgeGraphVRExporter } from '../src/services/vr-export-service.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const KG_FILE = path.join(ROOT, 'static', 'data', 'knowledge-graph.json');
const VR_DIR = path.join(ROOT, 'assets', 'vr');
const QUALITY = process.env.EXPORT_QUALITY || 'medium';
const FORMAT = (process.env.EXPORT_FORMAT || 'glb').toLowerCase();

function ensureGraphData() {
  if (fs.existsSync(KG_FILE)) {
    return JSON.parse(fs.readFileSync(KG_FILE, 'utf8'));
  }
  // KG json is gitignored (regenerated by CI); rebuild it on the fly.
  console.log('⚠️ knowledge-graph.json missing — regenerating via build-knowledge-graph.cjs');
  execFileSync('node', [path.join(ROOT, 'scripts', 'build-knowledge-graph.cjs')], {
    stdio: 'inherit',
    cwd: ROOT,
  });
  if (!fs.existsSync(KG_FILE)) {
    throw new Error(`Failed to produce ${KG_FILE}`);
  }
  return JSON.parse(fs.readFileSync(KG_FILE, 'utf8'));
}

async function main() {
  fs.mkdirSync(VR_DIR, { recursive: true });
  const graphData = ensureGraphData();

  const exporter = new KnowledgeGraphVRExporter({ quality: QUALITY });
  exporter.setGraphData(graphData);
  const { gltf, glb, stats } = await exporter.generateGLTF();

  if (FORMAT === 'glb' || FORMAT === 'both') {
    const buf = Buffer.from(glb instanceof ArrayBuffer ? glb : glb.buffer);
    fs.writeFileSync(path.join(VR_DIR, 'knowledge-graph.glb'), buf);
    console.log(`✅ Wrote knowledge-graph.glb (${buf.byteLength} bytes)`);
  }
  if (FORMAT === 'gltf' || FORMAT === 'both') {
    fs.writeFileSync(
      path.join(VR_DIR, 'knowledge-graph.gltf'),
      JSON.stringify(gltf, null, 2)
    );
    console.log('✅ Wrote knowledge-graph.gltf');
  }

  // Surface stats for the release body (consumed via $GITHUB_OUTPUT).
  const out = process.env.GITHUB_OUTPUT;
  if (out) {
    fs.appendFileSync(out, `NODE_COUNT=${stats.nodes}\n`);
    fs.appendFileSync(out, `EDGE_COUNT=${stats.edges}\n`);
    fs.appendFileSync(out, `FILE_SIZE=${stats.fileSize}\n`);
  }
  console.log(`🥽 VR scene: ${stats.nodes} nodes, ${stats.edges} edges`);
}

main().catch((err) => {
  console.error('❌ VR export failed:', err);
  process.exit(1);
});
